# Traffic simulation function

def simulate_traffic(
    strategy="fixed",
    simulation_time=600,
    seed=42
):

    rng = np.random.default_rng(seed)

    intersections = ["A", "B", "C", "D"]
    directions = ["North", "South", "East", "West"]

    # Create vehicle queues
    queues = {
        i: {d: [] for d in directions}
        for i in intersections
    }

    # Signal settings
    cycle_time = 60
    green_time = 30
    min_green = 10

    # Adaptive signal phases
    phases = {
        i: "NS" for i in intersections
    }

    waiting_times = []
    total_arrivals = 0
    total_departures = 0

    history = []

    for t in range(simulation_time):

        # Step 1: Generate vehicles
        for i in intersections:

            for d in directions:

                arrivals = rng.poisson(0.35)

                for _ in range(arrivals):
                    queues[i][d].append(t)

                total_arrivals += arrivals

        # Step 2: Control traffic signals
        for i in intersections:

            if strategy == "fixed":

                if (t % cycle_time) < green_time:
                    current_phase = "NS"
                else:
                    current_phase = "EW"

            elif strategy == "adaptive":

                # Re-evaluate every 10 seconds
                if t % min_green == 0:

                    ns_queue = (
                        len(queues[i]["North"]) +
                        len(queues[i]["South"])
                    )

                    ew_queue = (
                        len(queues[i]["East"]) +
                        len(queues[i]["West"])
                    )

                    if ns_queue >= ew_queue:
                        phases[i] = "NS"
                    else:
                        phases[i] = "EW"

                current_phase = phases[i]

            else:
                raise ValueError("Unknown strategy")

            # Step 3: Move vehicles through green signals
            if current_phase == "NS":
                active_directions = ["North", "South"]
            else:
                active_directions = ["East", "West"]

            for d in active_directions:

                # Maximum 2 vehicles per direction per second
                served = min(2, len(queues[i][d]))

                departed = queues[i][d][:served]

                # Calculate vehicle waiting time
                for arrival_time in departed:
                    waiting_times.append(t - arrival_time)

                queues[i][d] = queues[i][d][served:]

                total_departures += served

        # Step 4: Record traffic density
        total_queue = sum(
            len(queues[i][d])
            for i in intersections
            for d in directions
        )

        history.append({
            "Time": t,
            "Vehicles Waiting": total_queue,
            "Vehicles Passed": total_departures
        })

    # Final performance metrics
    avg_waiting = (
        np.mean(waiting_times)
        if waiting_times else 0
    )

    avg_queue = np.mean([
        row["Vehicles Waiting"] for row in history
    ])

    return {
        "Strategy": strategy,
        "Total Arrivals": total_arrivals,
        "Total Passed": total_departures,
        "Average Waiting Time": avg_waiting,
        "Average Queue": avg_queue,
        "History": pd.DataFrame(history)
    }


print("Traffic simulation function created!")

